-- 4. ENABLE ROW LEVEL SECURITY & POLICIES
-- ============================================================================

alter table public.schools enable row level security;
alter table public.profiles enable row level security;
alter table public.conversations enable row level security;
alter table public.messages enable row level security;

-- 4.1 SCHOOLS POLICIES
drop policy if exists "Schools: read own school" on public.schools;
create policy "Schools: read own school"
  on public.schools
  for select
  to authenticated
  using (id = public.current_school_id());

-- 4.2 PROFILES POLICIES
drop policy if exists "Profiles: read self or same school" on public.profiles;
create policy "Profiles: read self or same school"
  on public.profiles
  for select
  to authenticated
  using (id = auth.uid() or school_id = public.current_school_id());

drop policy if exists "Profiles: insert self" on public.profiles;
create policy "Profiles: insert self"
  on public.profiles
  for insert
  to authenticated
  with check (id = auth.uid());

drop policy if exists "Profiles: update self" on public.profiles;
create policy "Profiles: update self"
  on public.profiles
  for update
  to authenticated
  using (id = auth.uid())
  with check (id = auth.uid());

-- 4.3 CONVERSATIONS POLICIES
drop policy if exists "Conversations: participants read" on public.conversations;
create policy "Conversations: participants read"
  on public.conversations
  for select
  to authenticated
  using (
    (student_id = auth.uid() or counsellor_id = auth.uid())
    and school_id = public.current_school_id()
  );

drop policy if exists "Conversations: student insert own" on public.conversations;
create policy "Conversations: student insert own"
  on public.conversations
  for insert
  to authenticated
  with check (
    student_id = auth.uid()
    and school_id = public.current_school_id()
  );

drop policy if exists "Conversations: counsellor in same school update" on public.conversations;
create policy "Conversations: counsellor in same school update"
  on public.conversations
  for update
  to authenticated
  using (
    school_id = public.current_school_id()
    and (
      counsellor_id = auth.uid()
      or student_id = auth.uid()
      or exists (
        select 1
        from public.profiles p
        where p.id = auth.uid()
          and p.school_id = public.conversations.school_id
          and p.role in ('counsellor', 'admin')
      )
    )
  )
  with check (
    school_id = public.current_school_id()
  );

-- 4.4 MESSAGES POLICIES
drop policy if exists "Messages: participants read" on public.messages;
create policy "Messages: participants read"
  on public.messages
  for select
  to authenticated
  using (public.can_access_conversation(conversation_id));

drop policy if exists "Messages: participant insert own human message" on public.messages;
create policy "Messages: participant insert own human message"
  on public.messages
  for insert
  to authenticated
  with check (
    public.can_access_conversation(conversation_id)
    and sender_id = auth.uid()
    and is_ai = false
  );

drop policy if exists "Messages: service_role insert AI message" on public.messages;
create policy "Messages: service_role insert AI message"
  on public.messages
  for insert
  to service_role
  with check (
    is_ai = true
    and sender_id is null
  );

