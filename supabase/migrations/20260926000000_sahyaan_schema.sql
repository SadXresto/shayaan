-- ============================================================================
-- 1. TABLES (schools, profiles, conversations, messages)
-- ============================================================================

-- 1.1 SCHOOLS
create table if not exists public.schools (
  id uuid default gen_random_uuid() primary key,
  name text not null,
  slug text unique not null,
  invite_code text unique not null,
  email_domains text[] not null default '{}',
  created_at timestamptz not null default now()
);

-- 1.2 PROFILES (1-to-1 with auth.users)
create table if not exists public.profiles (
  id uuid references auth.users(id) on delete cascade primary key,
  role text not null default 'student'
    check (role in ('student', 'counselee', 'counsellor', 'admin')),
  full_name text,
  avatar_url text,
  bio text,
  is_available boolean not null default false,
  school_id uuid references public.schools(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 1.3 CONVERSATIONS
create table if not exists public.conversations (
  id uuid default gen_random_uuid() primary key,
  student_id uuid references public.profiles(id) on delete cascade not null,
  counsellor_id uuid references public.profiles(id) on delete set null,
  school_id uuid references public.schools(id) on delete cascade not null,
  is_ai boolean not null default false,
  status text not null default 'active'
    check (status in ('active', 'pending', 'closed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 1.4 MESSAGES (sender_id NULL + is_ai = true => Sage AI)
create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  conversation_id uuid references public.conversations(id) on delete cascade not null,
  sender_id uuid references public.profiles(id) on delete set null,
  content text not null,
  is_ai boolean not null default false,
  created_at timestamptz not null default now(),
  constraint messages_sender_ai_check check (
    (is_ai = true and sender_id is null) or
    (is_ai = false and sender_id is not null)
  )
);

-- ============================================================================
-- 2. INDEXES
-- ============================================================================

create index if not exists idx_profiles_school_role
  on public.profiles(school_id, role);

create index if not exists idx_conversations_student
  on public.conversations(student_id);

create index if not exists idx_conversations_counsellor
  on public.conversations(counsellor_id);

create index if not exists idx_conversations_school_status
  on public.conversations(school_id, status);

create index if not exists idx_messages_conversation_created
  on public.messages(conversation_id, created_at);

-- ============================================================================
-- 3. HELPER & RPC FUNCTIONS (all security definer with search_path = public)
-- ============================================================================

-- 3.1 Helper: current_school_id()
create or replace function public.current_school_id()
returns uuid
language sql
stable
security definer
set search_path = public
as $$
  select school_id
  from public.profiles
  where id = auth.uid();
$$;

-- 3.2 Helper: can_access_conversation(conv_id uuid)
create or replace function public.can_access_conversation(conv_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.conversations c
    where c.id = conv_id
      and (c.student_id = auth.uid() or c.counsellor_id = auth.uid())
      and c.school_id = public.current_school_id()
  );
$$;

-- 3.3 RPC: resolve_school_code(code text)
-- Returns the matching school row for student/counsellor invite-code login
drop function if exists public.resolve_school_code(text);
create or replace function public.resolve_school_code(code text)
returns setof public.schools
language sql
stable
security definer
set search_path = public
as $$
  select s.*
  from public.schools s
  where upper(trim(s.invite_code)) = upper(trim(code))
  limit 1;
$$;

-- 3.4 RPC: request_counsellor()
-- Picks an available counsellor in the caller's school (or the least-loaded
-- counsellor in that school), creates a conversation, and returns its UUID.
drop function if exists public.request_counsellor();
create or replace function public.request_counsellor()
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_school_id uuid;
  v_counsellor_id uuid;
  v_conversation_id uuid;
begin
  select p.school_id into v_school_id
  from public.profiles p
  where p.id = auth.uid();

  if v_school_id is null then
    raise exception 'User profile is not linked to a school';
  end if;

  -- Prefer an available counsellor with the fewest active conversations;
  -- fall back to any counsellor in the same school with the lowest active load.
  select p.id into v_counsellor_id
  from public.profiles p
  left join public.conversations c
    on c.counsellor_id = p.id
   and c.status = 'active'
  where p.school_id = v_school_id
    and p.role = 'counsellor'
  group by p.id, p.is_available
  order by p.is_available desc, count(c.id) asc, random()
  limit 1;

  insert into public.conversations (
    student_id,
    counsellor_id,
    school_id,
    is_ai,
    status
  )
  values (
    auth.uid(),
    v_counsellor_id,
    v_school_id,
    false,
    case when v_counsellor_id is null then 'pending' else 'active' end
  )
  returning id into v_conversation_id;

  return v_conversation_id;
end;
$$;

-- 3.5 Trigger Function: handle_new_user()
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_school_id uuid;
  v_role text;
  v_full_name text;
begin
  v_role := coalesce(nullif(trim(new.raw_user_meta_data->>'role'), ''), 'student');
  if v_role not in ('student', 'counselee', 'counsellor', 'admin') then
    v_role := 'student';
  end if;

  v_full_name := coalesce(
    nullif(trim(new.raw_user_meta_data->>'full_name'), ''),
    split_part(coalesce(new.email, 'Student'), '@', 1)
  );

  -- 1) Try school_id from signup metadata
  begin
    v_school_id := nullif(trim(new.raw_user_meta_data->>'school_id'), '')::uuid;
  exception when others then
    v_school_id := null;
  end;

  -- 2) Otherwise match by email domain against public.schools.email_domains
  if v_school_id is null and new.email is not null then
    select s.id into v_school_id
    from public.schools s
    where exists (
      select 1
      from unnest(s.email_domains) as domain
      where lower(split_part(new.email, '@', 2)) = lower(trim(domain))
    )
    limit 1;
  end if;

  insert into public.profiles (id, role, full_name, school_id)
  values (new.id, v_role, v_full_name, v_school_id)
  on conflict (id) do update
    set full_name = coalesce(excluded.full_name, public.profiles.full_name),
        school_id = coalesce(excluded.school_id, public.profiles.school_id),
        updated_at = now();

  return new;
end;
$$;

-- Attach trigger to auth.users
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

