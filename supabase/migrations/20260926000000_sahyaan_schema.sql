-- 1. SCHOOLS
create table public.schools (
  id uuid default gen_random_uuid() primary key,
  name text not null,
  slug text unique not null,
  invite_code text unique not null,
  email_domains text[] default '{}',
  created_at timestamptz default now()
);
alter table public.schools enable row level security;

-- 2. PROFILES
create table public.profiles (
  id uuid references auth.users on delete cascade primary key,
  role text not null default 'counselee'
    check (role in ('counselee', 'counsellor', 'admin')),
  full_name text,
  avatar_url text,
  bio text,
  is_available boolean default false,
  school_id uuid references public.schools(id) on delete set null,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);
alter table public.profiles enable row level security;

create function public.current_school_id() returns uuid
language sql stable security definer set search_path = public as $$
  select school_id from public.profiles where id = auth.uid();
$$;

create policy "Users see only their own school"
  on public.schools for select to authenticated
  using (id = public.current_school_id());

create policy "See profiles in own school"
  on public.profiles for select to authenticated
  using (school_id = public.current_school_id() or id = auth.uid());

create policy "Insert own profile"
  on public.profiles for insert with check (auth.uid() = id);

create policy "Update own profile"
  on public.profiles for update using (auth.uid() = id);

-- 3. CONVERSATIONS
create table public.conversations (
  id uuid default gen_random_uuid() primary key,
  counselee_id uuid references public.profiles(id) on delete cascade not null,
  counsellor_id uuid references public.profiles(id) on delete set null,
  school_id uuid references public.schools(id) on delete cascade not null,
  is_ai boolean default false,
  status text default 'active' check (status in ('active', 'pending', 'closed')),
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);
alter table public.conversations enable row level security;

create policy "See own conversations in own school"
  on public.conversations for select to authenticated
  using (
    (auth.uid() = counselee_id or auth.uid() = counsellor_id)
    and school_id = public.current_school_id()
  );

create policy "Counselee creates conversation in own school"
  on public.conversations for insert to authenticated
  with check (
    auth.uid() = counselee_id
    and school_id = public.current_school_id()
    and (
      counsellor_id is null
      or exists (
        select 1 from public.profiles c
        where c.id = counsellor_id
          and c.role = 'counsellor'
          and c.school_id = public.current_school_id()
      )
    )
  );

create policy "Participants update conversations"
  on public.conversations for update to authenticated
  using (
    (auth.uid() = counselee_id or auth.uid() = counsellor_id)
    and school_id = public.current_school_id()
  );

-- 4. MESSAGES
create table public.messages (
  id bigint generated by default as identity primary key,
  conversation_id uuid references public.conversations(id) on delete cascade not null,
  sender_id uuid references public.profiles(id) on delete set null,
  content text not null,
  is_ai boolean default false,
  created_at timestamptz default now()
);
alter table public.messages enable row level security;

create function public.can_access_conversation(conv_id uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.conversations c
    where c.id = conv_id
      and (c.counselee_id = auth.uid() or c.counsellor_id = auth.uid())
      and c.school_id = (select school_id from public.profiles where id = auth.uid())
  );
$$;

create policy "See messages in own school conversations"
  on public.messages for select to authenticated
  using (public.can_access_conversation(conversation_id));

create policy "Insert messages in own school conversations"
  on public.messages for insert to authenticated
  with check (public.can_access_conversation(conversation_id));

-- 5. AUTO-CREATE PROFILE ON SIGNUP
create function public.handle_new_user()
returns trigger as $$
declare
  v_school_id uuid;
  v_role text;
begin
  v_role := coalesce(new.raw_user_meta_data->>'role', 'counselee');
  v_school_id := nullif(new.raw_user_meta_data->>'school_id', '')::uuid;

  if v_school_id is null and new.email is not null then
    select s.id into v_school_id from public.schools s
    where exists (
      select 1 from unnest(s.email_domains) d
      where lower(new.email) like '%@' || lower(d)
    ) limit 1;
  end if;

  insert into public.profiles (id, full_name, role, school_id)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name', 'User'),
    v_role,
    v_school_id
  );
  return new;
end;
$$ language plpgsql security definer;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- 6. RPC: resolve_school_code
create function public.resolve_school_code(code text)
returns table (id uuid, name text)
language sql stable security definer set search_path = public as $$
  select s.id, s.name from public.schools s
  where upper(s.invite_code) = upper(code) limit 1;
$$;

-- 7. RPC: request_counsellor
create function public.request_counsellor()
returns uuid
language plpgsql security definer set search_path = public as $$
declare
  v_school uuid;
  v_counsellor uuid;
  v_conv uuid;
begin
  select school_id into v_school from public.profiles where id = auth.uid();
  if v_school is null then raise exception 'You are not linked to a school yet'; end if;

  select id into v_counsellor from public.profiles
   where school_id = v_school and role = 'counsellor' and is_available = true
   order by random() limit 1;

  insert into public.conversations (counselee_id, counsellor_id, school_id, status)
  values (
    auth.uid(), v_counsellor, v_school,
    case when v_counsellor is null then 'pending' else 'active' end
  )
  returning id into v_conv;

  return v_conv;
end;
$$;

-- 8. GRANTS (critical — RLS policies will fail without these)
grant execute on function public.current_school_id() to authenticated;
grant execute on function public.can_access_conversation(uuid) to authenticated;
grant execute on function public.resolve_school_code(text) to anon, authenticated;
grant execute on function public.request_counsellor() to authenticated;

